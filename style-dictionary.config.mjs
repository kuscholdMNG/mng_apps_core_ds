// Builds platform code from the DTCG tokens in tokens/.
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGBrandColors.swift            (UIKit + SwiftUI)
//            ../mng_apps_ios_ds/Tokens/MNGButtonTokens.swift           (button pilot, DEC-07)
//   Android -> ../mng_apps_android_ds/tokens/MngBrandColors.kt            (Jetpack Compose)
//              ../mng_apps_android_ds/tokens/res/values/mng_button.xml   (button pilot, DEC-07; View-based UI)
//              ../mng_apps_android_ds/tokens/flavors/<flavor>/res/values/mng_brand_colors.xml (one per Gradle flavor)
// Colors are written from the hex bytes (0xRRGGBB), never as rounded decimals, so iOS can't drift (DSC-01).
// Run: npm run tokens && npm run build
import StyleDictionary from 'style-dictionary';

const CORE = ['navbar', 'navtext', 'tabbar', 'tabactive', 'tabinactive', 'action', 'alert', 'alerttext'];
const HEADER = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-01..03). Do not edit by hand.\n';
const hex6 = (t) => t.$value.replace('#', '').slice(0, 6).toUpperCase();
const rgbc = (t) => { const h = hex6(t); return `rgb(${parseInt(h.slice(0,2),16)}, ${parseInt(h.slice(2,4),16)}, ${parseInt(h.slice(4,6),16)})`; };

// tokens grouped as { market: { role: token } } across the core + platform files
function byMarket(tokens) {
  const m = {};
  for (const t of tokens) {
    const [kind, group, market, role] = t.path; // color.<brand|ios|android>.<market>.<role>
    if (kind !== 'color' || !['brand', 'ios', 'android'].includes(group)) continue;
    (m[market] ??= {})[role] = t;
  }
  return Object.fromEntries(Object.entries(m).sort(([a], [b]) => a.localeCompare(b)));
}

StyleDictionary.registerFormat({
  name: 'mng/swift-palettes',
  format: ({ dictionary }) => {
    const M = byMarket(dictionary.allTokens);
    const roles = [...CORE, 'header'];
    let s = HEADER + 'import UIKit\nimport SwiftUI\n\n';
    s += '/// One market\'s brand colors. Core roles come from the Core library; `header` is iOS-only.\npublic struct MNGBrandPalette {\n';
    s += roles.map(r => `    public let ${r}: UIColor`).join('\n') + '\n    /// Alias of `action` (PLAT-04).\n    public var buy: UIColor { action }\n    /// Alias of `action` (PLAT-04).\n    public var continueButton: UIColor { action }\n}\n\n';
    s += 'public extension UIColor {\n    /// Exact sRGB color from 0xRRGGBB bytes.\n    convenience init(mngHex hex: UInt32) {\n        self.init(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255, blue: CGFloat(hex & 0xFF) / 255, alpha: 1)\n    }\n}\n\n';
    s += 'public extension MNGBrandPalette {\n    func color(_ keyPath: KeyPath<MNGBrandPalette, UIColor>) -> Color { Color(uiColor: self[keyPath: keyPath]) }\n}\n\n';
    s += 'public enum MNGBrandPalettes {\n';
    for (const [k, t] of Object.entries(M)) {
      const name = t.navbar?.$extensions?.mng?.market ?? k.toUpperCase();
      s += `    /// ${name} (${k.toUpperCase()})\n    public static let ${k} = MNGBrandPalette(\n`;
      s += roles.map(r => `        ${r}: UIColor(mngHex: 0x${hex6(t[r])})  /* ${t[r].$value} · ${rgbc(t[r])} */`).join(',\n') + '\n    )\n';
    }
    s += '\n    /// Palette for a market code, e.g. "TDP". Codes match the Gradle flavor names upper-cased.\n    public static func forMarket(_ code: String) -> MNGBrandPalette? {\n        switch code.lowercased() {\n';
    for (const k of Object.keys(M)) s += `        case "${k}": return ${k}\n`;
    s += '        default: return nil\n        }\n    }\n}\n';
    return s;
  },
});

StyleDictionary.registerFormat({
  name: 'mng/kotlin-palettes',
  format: ({ dictionary, options }) => {
    const M = byMarket(dictionary.allTokens);
    const roles = [...CORE, 'statusbar'];
    let s = HEADER + `package ${options.packageName}\n\nimport androidx.compose.ui.graphics.Color\n\n`;
    s += '/** One market\'s brand colors. Core roles come from the Core library; `statusbar` is Android-only. */\ndata class MngBrandPalette(\n';
    s += roles.map(r => `    val ${r}: Color`).join(',\n') + '\n) {\n    /** Alias of [action] (PLAT-04). */\n    val buy: Color get() = action\n    /** Alias of [action] (PLAT-04). */\n    val continueButton: Color get() = action\n}\n\n';
    s += 'object MngBrandPalettes {\n';
    for (const [k, t] of Object.entries(M)) {
      const name = t.navbar?.$extensions?.mng?.market ?? k.toUpperCase();
      s += `    /** ${name} (${k.toUpperCase()}) */\n    val ${k.toUpperCase()} = MngBrandPalette(\n`;
      s += roles.map((r, i) => `        ${r} = Color(0xFF${hex6(t[r])})${i < roles.length - 1 ? ',' : ''}  // ${t[r].$value} · ${rgbc(t[r])}`).join('\n') + '\n    )\n';
    }
    s += '\n    /** Palette for a market code or Gradle flavor name, e.g. "tdp". */\n    fun forMarket(code: String): MngBrandPalette? = when (code.lowercase()) {\n';
    for (const k of Object.keys(M)) s += `        "${k}" -> ${k.toUpperCase()}\n`;
    s += '        else -> null\n    }\n}\n';
    return s;
  },
});

StyleDictionary.registerFormat({
  name: 'mng/android-flavor-xml',
  format: ({ dictionary, options }) => {
    const t = byMarket(dictionary.allTokens)[options.market];
    const roles = [...CORE, 'statusbar'];
    let s = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-01..03). Do not edit by hand. -->\n';
    s += `<!-- ${t.navbar.$extensions.mng.market} (${options.market.toUpperCase()}) -->\n<resources>\n`;
    s += roles.map(r => `    <color name="mng_brand_${r}">#FF${hex6(t[r])}</color> <!-- ${rgbc(t[r])} -->`).join('\n');
    s += '\n    <color name="mng_brand_buy">@color/mng_brand_action</color>\n    <color name="mng_brand_continue">@color/mng_brand_action</color>\n</resources>\n';
    return s;
  },
});


// ---- Button pilot (DEC-07) -------------------------------------------------
const BTN_HEADER = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-07). Do not edit by hand.\n';
const px = (t) => parseFloat(String(t.$value).replace('px', ''));
const find = (all, path) => all.find(t => t.path.join('.') === path);

StyleDictionary.registerFormat({
  name: 'mng/swift-button',
  format: ({ dictionary }) => {
    const A = dictionary.allTokens, g = (p) => find(A, p);
    const r = g('button.ios.primary.radius'), rl = g('button.ios.primary.radius-legacy'), bl = g('button.ios.primary.border-legacy'), h = g('button.ios.primary.height');
    const lab = g('button.ios.primary.label'), link = g('button.ios.link.label');
    const legacy = rl.$extensions.mng.markets.map(c => `"${c.toLowerCase()}"`).join(', ');
    const links = A.filter(t => t.path[0] === 'button' && t.path[1] === 'ios' && t.path[2] === 'link' && t.path[3] === 'color').sort((a, b) => a.path[4].localeCompare(b.path[4]));
    const col = (p) => { const t = g(p); return `UIColor(mngHex: 0x${hex6(t)})  /* ${t.$value} · ${rgbc(t)} */`; };
    let s = BTN_HEADER + 'import UIKit\n\n/// Button tokens (Core + iOS). Spec: mng_apps_core_ds/docs/components/BUTTON.md\npublic enum MNGButtonTokens {\n';
    s += `    /// Primary label color. Core \`button.primary.label\`. Fails 4.5:1 in some markets (IMPROVEMENTS CLR-04).\n    public static let primaryLabel = ${col('button.primary.label')}\n`;
    s += `    /// Disabled fill. Core \`button.disabled.fill\`.\n    public static let disabledFill = ${col('button.disabled.fill')}\n`;
    s += `    /// Disabled label. Core \`button.disabled.label\`.\n    public static let disabledLabel = ${col('button.disabled.label')}\n\n`;
    s += `    /// Corner radius, standard template.\n    public static let cornerRadius: CGFloat = ${px(r)}\n    /// Corner radius, legacy template markets.\n    public static let cornerRadiusLegacy: CGFloat = ${px(rl)}\n    /// Border in the fill color, legacy template markets.\n    public static let borderWidthLegacy: CGFloat = ${px(bl)}\n`;
    s += `    /// Height. PROVISIONAL: not in the source (MISSING-ASSETS 5.5). Future: BTN-01.\n    public static let height: CGFloat = ${px(h)}\n\n`;
    s += `    /// Legacy-template markets (radius ${px(rl)} + ${px(bl)} pt border).\n    public static let legacyMarkets: Set<String> = [${legacy}]\n`;
    s += '    public static func isLegacy(_ market: String) -> Bool { legacyMarkets.contains(market.lowercased()) }\n';
    s += '    public static func cornerRadius(forMarket market: String) -> CGFloat { isLegacy(market) ? cornerRadiusLegacy : cornerRadius }\n';
    s += '    public static func borderWidth(forMarket market: String) -> CGFloat { isLegacy(market) ? borderWidthLegacy : 0 }\n\n';
    s += `    /// Label font: ${lab.$extensions.mng.postscript} ${px({ $value: lab.$value.fontSize })}, uppercase. Falls back to the bold system font at the same size.\n`;
    s += `    public static var labelFont: UIFont { UIFont(name: "${lab.$extensions.mng.postscript}", size: ${px({ $value: lab.$value.fontSize })}) ?? .boldSystemFont(ofSize: ${px({ $value: lab.$value.fontSize })}) }\n`;
    s += `    /// Text link font. PROVISIONAL (MISSING-ASSETS 5.5).\n    public static var linkFont: UIFont { UIFont(name: "${link.$extensions.mng.postscript}", size: ${px({ $value: link.$value.fontSize })}) ?? .systemFont(ofSize: ${px({ $value: link.$value.fontSize })}) }\n\n`;
    s += '    /// Text link color per market (iOS `paywallLinkColor`, shipped).\n    public static func linkColor(forMarket market: String) -> UIColor? {\n        switch market.lowercased() {\n';
    for (const t of links) s += `        case "${t.path[4]}": return UIColor(mngHex: 0x${hex6(t)})  // ${t.$value} · ${rgbc(t)}\n`;
    s += '        default: return nil\n        }\n    }\n}\n';
    return s;
  },
});

StyleDictionary.registerFormat({
  name: 'mng/android-button-xml',
  format: ({ dictionary }) => {
    const A = dictionary.allTokens, g = (p) => find(A, p);
    const lab = g('button.android.primary.label'), link = g('button.android.link.label');
    const c = (name, p) => { const t = g(p); return `    <color name="${name}">#FF${hex6(t)}</color> <!-- ${rgbc(t)} · ${p} -->`; };
    let s = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-07). Do not edit by hand. Spec: mng_apps_core_ds/docs/components/BUTTON.md -->\n<resources>\n';
    s += [c('mng_button_primary_label', 'button.primary.label'), c('mng_button_disabled_fill', 'button.disabled.fill'), c('mng_button_disabled_label', 'button.disabled.label'), c('mng_button_link', 'button.android.link.color')].join('\n') + '\n';
    s += `    <dimen name="mng_button_primary_height">${px(g('button.android.primary.height'))}dp</dimen>\n`;
    s += `    <dimen name="mng_button_primary_corner_radius">${px(g('button.android.primary.radius'))}dp</dimen>\n`;
    s += `    <!-- Label size and weight PROVISIONAL (MISSING-ASSETS 5.5): Material Button default. Future: BTN-02. -->\n    <dimen name="mng_button_primary_text_size">${px({ $value: lab.$value.fontSize })}sp</dimen>\n`;
    s += `    <item name="mng_button_primary_letter_spacing" format="float" type="dimen">${lab.$extensions.mng.letterSpacingEm}</item>\n`;
    s += `    <dimen name="mng_button_link_text_size">${px({ $value: link.$value.fontSize })}sp</dimen>\n</resources>\n`;
    return s;
  },
});

const coreJson = JSON.parse(await (await import('node:fs/promises')).readFile('tokens/core/brand.tokens.json', 'utf8'));
const markets = Object.keys(coreJson.color.brand).sort();

const sd = new StyleDictionary({
  source: ['tokens/core/**/*.json', 'tokens/ios/**/*.json', 'tokens/android/**/*.json'],
  log: { warnings: 'disabled' },
  platforms: {
    ios: {
      buildPath: '../mng_apps_ios_ds/Tokens/',
      files: [
        { destination: 'MNGBrandColors.swift', format: 'mng/swift-palettes', filter: (t) => t.path[1] !== 'android' },
        { destination: 'MNGButtonTokens.swift', format: 'mng/swift-button', filter: (t) => t.path[0] === 'button' && t.path[1] !== 'android' },
      ],
    },
    android: {
      buildPath: '../mng_apps_android_ds/tokens/',
      files: [
        { destination: 'res/values/mng_button.xml', format: 'mng/android-button-xml', filter: (t) => t.path[0] === 'button' && t.path[1] !== 'ios' },
        { destination: 'MngBrandColors.kt', format: 'mng/kotlin-palettes', options: { packageName: 'com.mng.designsystem.tokens' }, filter: (t) => t.path[1] !== 'ios' },
        ...markets.map(m => ({ destination: `flavors/${m}/res/values/mng_brand_colors.xml`, format: 'mng/android-flavor-xml', options: { market: m }, filter: (t) => t.path[1] !== 'ios' })),
      ],
    },
  },
});
await sd.buildAllPlatforms();
console.log('Built Swift (palettes + button), Kotlin, button XML and', markets.length, 'flavor XML files');

"""Build the to-do list of everything still to build in Figma and export to GitHub.
Usage: python3 scripts/build_backlog.py   (run after build_registry.py)
Reads:  data/registry.json (every item and its owner), data/backlog-status.json (build status, kept by hand)
Writes: data/backlog.json, docs/BACKLOG.md
To mark progress, edit data/backlog-status.json and re-run.
"""
import json
from collections import Counter
REG = json.load(open('data/registry.json'))['items']
S = json.load(open('data/backlog-status.json'))
ICON = S['statuses']; COLS = ['figma', 'tokens', 'code']
OWNER = {'core': 'Core', 'core+variant': 'Core + variant', 'ios': 'iOS only', 'android': 'Android only'}
WHERE = {'core': 'Core', 'core+variant': 'Core + iOS + Android', 'ios': 'iOS', 'android': 'Android'}

rows = []
for f in S['foundations']:
    rows.append({'id': f['id'], 'area': 'Foundations', 'group': f['group'], 'name': f['name'], 'owner': f['owner'],
                 **{c: f[c] for c in COLS}, 'blocked_by': f.get('blocked_by', ''), 'note': f.get('note', '')})
for it in REG:
    st = {**S['defaults'][it['type']], **S['items'].get(it['id'], {})}
    area = {'color-role': 'Color roles', 'icon': 'Icons', 'component': 'Components', 'layout': 'Layout'}[it['type']]
    rows.append({'id': it['id'], 'area': area, 'group': it['group'], 'name': it['name'], 'owner': it['owner'],
                 **{c: st[c] for c in COLS}, 'blocked_by': st.get('blocked_by', ''), 'note': st.get('note', '') or it.get('note', '')})
def overall(r):
    v = [r[c] for c in COLS if r[c] != 'na']
    if not v: return 'n/a'
    if all(x == 'done' for x in v): return 'done'
    if all(x in ('done', 'written') for x in v): return 'built'
    if any(x == 'blocked' for x in v) and not any(x in ('done', 'partial', 'written') for x in v): return 'blocked'
    if all(x == 'todo' for x in v): return 'todo'
    return 'in progress'
for r in rows: r['overall'] = overall(r)
json.dump({'generated_by': 'scripts/build_backlog.py', 'items': rows}, open('data/backlog.json', 'w'), indent=1, ensure_ascii=False)

areas = ['Foundations', 'Color roles', 'Components', 'Layout', 'Icons']
L = ['# Backlog — what is left to build in Figma and export to GitHub', '',
     'Generated by `scripts/build_backlog.py` from `data/registry.json` (every item found in the iOS and Android style guides) and `data/backlog-status.json` (build status, kept by hand). Do not edit this file; edit the status file and re-run.', '',
     '**Columns.** ' + ' · '.join(f"**{c.capitalize()}**: {S['columns'][c]}" for c in COLS), '',
     '**Status.** ' + ' · '.join(ICON.values()) + '. "Where" = which Figma files it goes in (from the owner in the registry).', '',
     '## Summary', '', 'Built = done everywhere except the code is not compiled in an app yet.', '', '| Area | Items | Done | Built | In progress | To do | Blocked |', '|---|---|---|---|---|---|---|']
for a in areas:
    rs = [r for r in rows if r['area'] == a and r['overall'] != 'n/a']; c = Counter(r['overall'] for r in rs)
    L.append(f"| {a} | {len(rs)} | {c['done']} | {c['built']} | {c['in progress']} | {c['todo']} | {c['blocked']} |")
c = Counter(r['overall'] for r in rows if r['overall'] != 'n/a')
L.append(f"| **Total** | **{sum(c.values())}** | **{c['done']}** | **{c['built']}** | **{c['in progress']}** | **{c['todo']}** | **{c['blocked']}** |")
L += ['', '## Suggested order', ''] + [f'{i}. {s}' for i, s in enumerate(S['next'], 1)] + ['']
for a in areas:
    rs = [r for r in rows if r['area'] == a]
    L += [f'## {a}', '']
    for g in dict.fromkeys(r['group'] for r in rs):
        gr = [r for r in rs if r['group'] == g]
        L += [f'### {g}', ''] if g != a else []
        L += ['| Item | Where | Figma | Tokens | Code | Blocked by / note |', '|---|---|---|---|---|---|']
        for r in gr:
            note = ' · '.join(x for x in [('⛔ ' + r['blocked_by']) if r['blocked_by'] else '', r['note']] if x)
            L.append(f"| {r['name']} | {WHERE[r['owner']]} | {ICON[r['figma']]} | {ICON[r['tokens']]} | {ICON[r['code']]} | {note} |")
        L.append('')
open('docs/BACKLOG.md', 'w').write('\n'.join(L))
print(sum(c.values()), 'items (n/a excluded):', dict(c))

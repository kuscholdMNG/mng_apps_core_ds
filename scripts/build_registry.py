"""Build data/registry.json: every token role, icon and component with one owner (docs/ARCHITECTURE.md §1).
Usage: python3 scripts/build_registry.py
Reads data/icon-platform-map.json, data/component-platform-map.json and COLOR_ROLES below.
Writes data/registry.json and docs/REGISTRY.md. Owner: core | core+variant | ios | android.
"""
import json, re
from collections import Counter
ICON_OWNER = {"core": "core", "core-variant": "core+variant", "ios-only": "ios", "android-only": "android"}
# id, owner, iOS source, Android source, note   (from docs/PLATFORM-OWNERSHIP.md; status follows PLAT- decisions)
COLOR_ROLES = [
 ("color/navbar", "core", "navigationBarBackgroundColor", "Toolbar_Background", ""),
 ("color/navtext", "core", "navigationBarTitleColor", "Toolbar_Text_Primary", ""),
 ("color/tabbar", "core", "tabBarBackgroundColor", "NavigationBar_Background", ""),
 ("color/tabactive", "core", "tabBarSelectedTintColor", "NavigationBar_Icon_ActiveTintColor", ""),
 ("color/tabinactive", "core", "tabBarUnselectedTintColor", "NavigationBar_Icon_InactiveTintColor", ""),
 ("color/action", "core", "paywallPrimaryActionColor", "Paywall_PurchaseButton_Background", ""),
 ("color/alert", "core", "breakingNewsBannerBackgroundColor", "br_news_red", "One value proposed (PLAT-03)"),
 ("color/buy", "core", "paywallViewPurchaseButtonColor", "Paywall_BuyButton_Background", "Alias of action proposed (PLAT-04)"),
 ("color/continue", "core", "—", "btn_continue", "Alias of action proposed (PLAT-04)"),
 ("color/header", "ios", "cell-tertiary-headerBg", "—", "Defaults to navbar (PLAT-05)"),
 ("color/statusbar", "android", "—", "MainStyle_Primary_Dark", "Defaults to navbar (PLAT-05)"),
 ("color/accent", "android", "alertTopicCellSwitchTint", "MainStyle_Accent", "Switch color open (PLAT-10)"),
]
slug = lambda s: re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
reg = []
for r in COLOR_ROLES:
    reg.append({"id": r[0], "type": "color-role", "group": "Color", "name": r[0].split("/")[1], "owner": r[1],
                "ios": {"source": r[2]}, "android": {"source": r[3]}, "note": r[4], "core": {"figma": None, "spec": None}})
for i in json.load(open("data/icon-platform-map.json"))["purposes"]:
    reg.append({"id": "icon/" + slug(i["purpose"]), "type": "icon", "group": "Icons · " + i["group"], "name": i["purpose"],
                "owner": ICON_OWNER[i["bucket"]], "ios": {"source": i["ios_today"], "native": i["sf_symbol"]},
                "android": {"source": i["android_today"], "native": i["material"]}, "note": i["note"], "core": {"figma": None, "spec": None}})
for c in json.load(open("data/component-platform-map.json"))["items"]:
    reg.append({"id": ("layout/" if c["group"] == "Layout" else "component/") + c["id"], "type": "layout" if c["group"] == "Layout" else "component",
                "group": c["group"], "name": c["name"], "owner": c["owner"], "ios": {"source": c["ios_today"]},
                "android": {"source": c["android_today"]}, "note": c["note"], "core": {"figma": None, "spec": None}})
ids = [r["id"] for r in reg]; assert len(ids) == len(set(ids)), "duplicate ids"
summary = {t: dict(Counter(r["owner"] for r in reg if r["type"] == t)) for t in ("color-role", "icon", "component", "layout")}
json.dump({"generated_by": "scripts/build_registry.py", "summary": summary, "items": reg}, open("data/registry.json", "w"), indent=1)
LABEL = {"core": "Core", "core+variant": "Core + variant", "ios": "iOS only", "android": "Android only"}
md = ["# Registry — where everything lives", "", "Generated by `scripts/build_registry.py` from `data/registry.json`. Don't edit by hand.", "",
      "| Type | Core | Core + variant | iOS only | Android only |", "|---|---|---|---|---|"]
for t, s in summary.items(): md.append(f"| {t} | {s.get('core',0)} | {s.get('core+variant',0)} | {s.get('ios',0)} | {s.get('android',0)} |")
g = None
for r in reg:
    if r["group"] != g:
        g = r["group"]; md += ["", f"## {g}", "", "| Item | Owner | iOS | Android | Note |", "|---|---|---|---|---|"]
    cell = lambda x: (x or "—").replace("|", "/")
    md.append(f"| {r['name']} | {LABEL[r['owner']]} | {cell(r['ios'].get('source'))} | {cell(r['android'].get('source'))} | {cell(r['note'])} |")
open("docs/REGISTRY.md", "w").write("\n".join(md) + "\n")
print(summary, len(reg))

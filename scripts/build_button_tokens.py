"""Button pilot (DEC-07): tokens, spec data and docs from shipped values + Karl's decisions.
Usage: python3 scripts/build_button_tokens.py   (run after build_tokens.py, before `npm run build`)
Reads:  tokens/core/brand.tokens.json, data/source/button-shipped.json, data/button-decisions.json,
        data/source/markets.json (iOS paywallLinkColor)
Writes: tokens/core/button.tokens.json      button.<part>            (shared by both apps)
        tokens/ios/button.tokens.json       button.ios.*             (iOS radius, height, font, link color per market)
        tokens/android/button.tokens.json   button.android.*         (Android radius, height, font, link)
        data/button-spec.json               everything the Figma page and docs show, per market
        docs/components/BUTTON.md           the spec (generated)
        docs/IMPROVEMENTS.md                CLR-04 table between the BUTTON-CLR-04 markers (generated)
Colors carry hex ($value) and RGB 0-255 ($extensions.mng.rgb). Shipped colors are kept (DEC-07); failures are reported, never fixed here.
"""
import json, re

BRAND = json.load(open('tokens/core/brand.tokens.json'))['color']['brand']
SHIP = json.load(open('data/source/button-shipped.json'))
DEC = json.load(open('data/button-decisions.json'))
IOS = json.load(open('data/source/markets.json'))
P = DEC['provisional']
WHITE = '#ffffff'

rgb = lambda h: [int(h[i:i+2], 16) for i in (1, 3, 5)]
def lum(h):
    c = [x / 255 for x in rgb(h)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def ratio(a, b):
    x, y = lum(a), lum(b)
    return round((max(x, y) + 0.05) / (min(x, y) + 0.05), 2)

# OKLab darken: lower L (keep hue and chroma) until the color reaches 4.5:1 against white. Suggestion only (CLR-04).
def _lin(x): return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
def _gam(x): x = min(max(x, 0), 1); return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
def to_oklab(h):
    r, g, b = [_lin(v / 255) for v in rgb(h)]
    l = (0.4122214708*r + 0.5363325363*g + 0.0514459929*b) ** (1/3)
    m = (0.2119034982*r + 0.6806995451*g + 0.1073969566*b) ** (1/3)
    s = (0.0883024619*r + 0.2817188376*g + 0.6299787005*b) ** (1/3)
    return (0.2104542553*l + 0.7936177850*m - 0.0040720468*s, 1.9779984951*l - 2.4285922050*m + 0.4505937099*s, 0.0259040371*l + 0.7827717662*m - 0.8086757660*s)
def from_oklab(L, a, b):
    l = (L + 0.3963377774*a + 0.2158037573*b) ** 3; m = (L - 0.1055613458*a - 0.0638541728*b) ** 3; s = (L - 0.0894841775*a - 1.2914855480*b) ** 3
    r = 4.0767416621*l - 3.3077115913*m + 0.2309699292*s; g = -1.2684380046*l + 2.6097574011*m - 0.3413193965*s; bb = -0.0041960863*l - 0.7034186147*m + 1.7076147010*s
    return '#' + ''.join(f'{round(_gam(v) * 255):02x}' for v in (r, g, bb))
def darken_for(h, against=WHITE, target=4.5):
    L, a, b = to_oklab(h)
    while L > 0 and ratio(from_oklab(L, a, b), against) < target: L -= 0.002
    return from_oklab(L, a, b)

def ctok(hexv, desc, **ext): return {'$value': hexv, '$type': 'color', '$description': desc, '$extensions': {'mng': dict(rgb=rgb(hexv), **ext)}}
def dtok(v, desc, **ext): return {'$value': f'{v}px', '$type': 'dimension', '$description': desc, '$extensions': {'mng': ext}}
def ftok(family, weight, size, desc, **ext): return {'$value': {'fontFamily': family, 'fontWeight': weight, 'fontSize': f'{size}px'}, '$type': 'typography', '$description': desc, '$extensions': {'mng': ext}}

si, sa = SHIP['primary']['ios'], SHIP['primary']['android']
legacy = sorted(m['code'] for m in IOS['markets'] if m['template'] == 'legacy')
meta = {'$description': 'Generated by scripts/build_button_tokens.py (DEC-07). Do not edit by hand.'}

core = {'button': {
    'primary': {'label': ctok(WHITE, 'Primary button label (white on action). Both apps ship white. Fails 4.5:1 in some markets: IMPROVEMENTS CLR-04.', owner='core', shipped={'ios': WHITE, 'android': WHITE})},
    'disabled': {
        'fill': ctok(P['disabled']['fill'], 'Disabled button fill. Shipped on Android (Your News Continue); new on iOS.', owner='core', source='android'),
        'label': ctok(P['disabled']['label'], 'Disabled button label. Shipped on Android (Text_Disabled_Font).', owner='core', source='android')},
}}
iosb = {'button': {'ios': {
    'primary': {
        'radius': dtok(si['radius'], 'Corner radius, standard template (preferredButtonCornerRadius).', shipped=True),
        'radius-legacy': dtok(si['radius_legacy'], 'Corner radius, legacy template markets.', shipped=True, markets=legacy),
        'border-legacy': dtok(si['border_legacy'], 'Border in the fill color, legacy template markets.', shipped=True, markets=legacy),
        'height': dtok(P['ios_height']['value'], 'Height. PROVISIONAL: ' + P['ios_height']['why'], provisional=True),
        'label': ftok('Open Sans', 700, si['font']['size'], 'Label: OpenSans-Bold 14, uppercase.', postscript=si['font']['postscript'], textCase='uppercase', shipped=True)},
    'link': {
        'label': ftok('Open Sans', 400, P['ios_link_font']['size'], 'Text link label. PROVISIONAL: ' + P['ios_link_font']['why'], postscript=P['ios_link_font']['postscript'], provisional=True),
        'color': {}},
}}}
andb = {'button': {'android': {
    'primary': {
        'radius': dtok(sa['radius'], 'Corner radius: square (radius-paywall).', shipped=True),
        'height': dtok(sa['height'], 'Height (paywall_button_height).', shipped=True),
        'label': ftok(P['android_label_font']['family'], 500, P['android_label_font']['size'], 'Label: system font, uppercase. Weight and size PROVISIONAL: ' + P['android_label_font']['why'], textCase='uppercase', letterSpacingEm=P['android_label_font']['letter_spacing_em'], provisional=True)},
    'link': {
        'color': ctok('#000000', 'Text link (Paywall_Text), underlined.', shipped=True, underline=True),
        'label': ftok('Roboto', 400, 16, 'Text link: system sans 16sp, underlined.', shipped=True, underline=True)},
}}}

ios_by = {m['code'].lower(): m for m in IOS['markets']}
LINK = IOS['tokens'].index('paywallLinkColor')
rows = []
for k, roles in sorted(BRAND.items()):
    act = roles['action']['$value']; name = roles['action']['$extensions']['mng']['market']
    if k in ios_by:
        link = ios_by[k]['values'][LINK]; link_src = 'paywallLinkColor (shipped)'
    else:
        link = act; link_src = 'provisional market: follows action'
    iosb['button']['ios']['link']['color'][k] = ctok(link, f'{name}: iOS text link color. {link_src}.', market=name, shipped=k in ios_by, contrastOnWhite=ratio(link, WHITE))
    cw = ratio(WHITE, act); cl = ratio(link, WHITE)
    rows.append({'code': k.upper(), 'market': name, 'action': act, 'action_rgb': rgb(act), 'label_contrast': cw, 'label_pass': cw >= 4.5,
                 'suggested_action': None if cw >= 4.5 else darken_for(act), 'ios_link': link, 'ios_link_rgb': rgb(link), 'ios_link_contrast': cl, 'ios_link_pass': cl >= 4.5,
                 'suggested_link': None if cl >= 4.5 else darken_for(link), 'ios_radius': si['radius_legacy'] if k.upper() in legacy else si['radius'],
                 'ios_border': si['border_legacy'] if k.upper() in legacy else 0, 'legacy_template': k.upper() in legacy, 'provisional_market': roles['action']['$extensions']['mng'].get('provisional', False)})

json.dump({**meta, **core}, open('tokens/core/button.tokens.json', 'w'), indent=1)
json.dump({**meta, **iosb}, open('tokens/ios/button.tokens.json', 'w'), indent=1)
json.dump({**meta, **andb}, open('tokens/android/button.tokens.json', 'w'), indent=1)

disabled_c = ratio(P['disabled']['label'], P['disabled']['fill'])
spec = {**meta, 'decision': DEC['decision'], 'date': DEC['date'], 'rules': DEC['rules'], 'scope': DEC['scope'], 'legacy_markets': legacy,
        'anatomy': ['Container (fill = Brand theme action; disabled = button/disabled/fill)', 'Label (uppercase; color = button/primary/label; disabled = button/disabled/label)', 'iOS legacy markets only: 1 pt border in the fill color'],
        'platform': {
            'ios': {'radius': si['radius'], 'radius_legacy': si['radius_legacy'], 'border_legacy': si['border_legacy'], 'height': P['ios_height']['value'], 'height_provisional': True,
                    'label': 'Open Sans Bold 14, uppercase', 'link': 'paywallLinkColor per market, Open Sans Regular 14 (provisional), no underline', 'pressed': 'UIKit filled-button highlight (system)'},
            'android': {'radius': sa['radius'], 'height': sa['height'], 'height_provisional': False, 'label': 'Roboto Medium 14sp, uppercase (weight and size provisional)',
                        'link': '#000000, system 16sp, underlined', 'pressed': 'Material ripple (system)'}},
        'disabled': {'fill': P['disabled']['fill'], 'label': P['disabled']['label'], 'contrast': disabled_c, 'note': 'Disabled controls are exempt from WCAG 1.4.3.'},
        'markets': rows,
        'summary': {'markets': len(rows), 'label_fail': [r['code'] for r in rows if not r['label_pass']], 'ios_link_fail': [r['code'] for r in rows if not r['ios_link_pass']]}}
json.dump(spec, open('data/button-spec.json', 'w'), indent=1)

f = lambda h: f"`{h}` · {', '.join(map(str, rgb(h)))}"
fails = [r for r in rows if not r['label_pass']]
lfails = [r for r in rows if not r['ios_link_pass']]

